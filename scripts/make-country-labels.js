// Generates src/utilities/country-labels-{nn,se}.ts from the CLDR region names
// shipped with Node's ICU. Browsers do not carry CLDR data for these languages
// (Chrome resolves `nn` and `se` to English), so the tables are generated here
// and committed. Bokmål (country-labels-no.ts) and English stay hand-curated
// and fill any code CLDR lacks.
//
// Usage: pnpm make-country-labels   (needs a Node built with full ICU)
import { readFileSync, writeFileSync } from 'node:fs';
import process from 'node:process';
import { getCountries } from 'libphonenumber-js';

const nbSource = readFileSync(
  new URL('../src/utilities/country-labels-no.ts', import.meta.url),
  'utf8'
);
const nb = Object.fromEntries(
  [...nbSource.matchAll(/^\s+([A-Z]{2}): '((?:[^'\\]|\\.)*)',$/gm)].map((m) => [
    m[1],
    m[2].replace(/\\(.)/g, '$1'),
  ])
);

const targets = {
  nn: { name: 'countryLabelsNn', note: 'Nynorsk' },
  se: { name: 'countryLabelsSe', note: 'Northern Sami: needs native review' },
};

for (const [lang, { name, note }] of Object.entries(targets)) {
  const names = new Intl.DisplayNames([lang], {
    type: 'region',
    fallback: 'none',
  });
  const resolved = names.resolvedOptions().locale;
  if (!resolved.startsWith(lang)) {
    throw new Error(
      `This Node has no CLDR region names for "${lang}" (resolved ${resolved}); use a full-ICU build.`
    );
  }
  let fallbacks = 0;
  const lines = getCountries()
    .sort()
    .map((iso) => {
      let value;
      try {
        value = names.of(iso);
      } catch {
        value = undefined;
      }
      if (!value) {
        fallbacks++;
        value = nb[iso] ?? iso;
      }
      // Escape backslashes before quotes, so a name ending in `\` cannot
      // turn the closing quote into an escaped one.
      return `  ${iso}: '${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}',`;
    });
  const out = `// Generated by scripts/make-country-labels.js from the CLDR region names in
// Node's ICU ${process.versions.icu} (${note}). Codes CLDR lacks fall back to
// the bokmål table. Do not edit by hand; re-run \`pnpm make-country-labels\`.
import { type CountryCode } from './get-countries';

export const ${name}: Record<CountryCode, string> = {
${lines.join('\n')}
};
`;
  writeFileSync(
    new URL(`../src/utilities/country-labels-${lang}.ts`, import.meta.url),
    out
  );
  console.log(
    `${lang}: ${lines.length} names, ${fallbacks} from the bokmål table`
  );
}
